const opts = a => a.map((t,i)=>[String(i),t]);
const labels={single:'單選判斷',boolean:'是非辨析',multiple:'多選',fill:'關鍵詞填答',match:'點選配對',order:'流程排序',evidence:'證據拼圖',diagram:'圖像標示',repair:'錯誤訂正',decision:'情境決策'};
function choice(kind,title,items,answer,explanation){return {kind,label:labels[kind],title,instruction:kind==='multiple'?'選出所有符合資料的選項。':'選出最符合證據的一項。',options:opts(items),answer:Array.isArray(answer)?answer.map(String):String(answer),explanation};}
function parts(kind,title,rows,items,answers,explanation){return {kind,label:labels[kind],title,instruction:kind==='fill'?'在空格輸入課程中的關鍵詞。':kind==='diagram'?'依示意圖的位置，標上對應的概念。':'完成每一個部分，再檢查整組答案。',rows:opts(rows),options:opts(items),answer:Object.fromEntries(answers.map((a,i)=>[String(i),kind==='fill'?a:String(a)])),explanation};}
const C=(t,o,a,e)=>choice('single',t,o,a,e),M=(t,o,a,e)=>choice('multiple',t,o,a,e),B=(t,a,e)=>choice('boolean',t,['正確','錯誤'],a?0:1,e),P=(k,t,r,o,a,e)=>parts(k,t,r,o,a,e);
const O=(t,o,e)=>({...choice('order',t,o,o.map((_,i)=>i),e),instruction:'依序點選卡片；點選已放入的步驟可以撤回。'});
const D=(t,o,a,e)=>({kind:'decision',label:'情境決策',title:t,instruction:'先選擇判斷或行動，再選出支持理由；兩部分都完成後檢查。',rows:[['action','我的判斷／行動'],['reason','支持理由']],groups:{action:opts(o),reason:opts([e,'只要外觀相似，就能判定所有成分相同','只要得到一個結果，就不必檢查其他證據'])},answer:{action:String(a),reason:'0'},explanation:e}),R=(t,r,o,a,e)=>P('repair',t,r,o,a,e);
